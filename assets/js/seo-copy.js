export function getSeoCopy(pathname) {
  const normalizedPath = pathname.replace(/^\/ko(?=\/|$)/, '').replace(/^\//, '') || 'index.html';
  return SEO_COPY[normalizedPath] ?? null;
}

export function localePathFor(pathname, locale) {
  const englishPath = pathname.replace(/^\/ko(?=\/|$)/, '') || '/';
  return locale === 'ko' ? `/ko${englishPath === '/' ? '/' : englishPath}` : englishPath;
}

export function applySeoDocumentCopy(document, locale) {
  const copy = getSeoCopy(document.location?.pathname ?? '');
  if (!copy) return;
  document.title = copy.title[locale];
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = copy.description[locale];
  const heading = document.querySelector('#directory-title') ?? document.querySelector('.tool-heading h1');
  const lead = document.querySelector('.section-heading > p[data-i18n="subtitle"]') ?? document.querySelector('.tool-heading h1 + p');
  if (heading && copy.heading) heading.textContent = copy.heading[locale];
  if (lead && copy.lead) lead.textContent = copy.lead[locale];
}
